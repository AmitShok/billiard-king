local order = {}
for k, _ in pairs(G) do order[#order + 1] = k end
table.sort(order)

local CELL_W, CELL_H, COLS = 6, 9, 16
local rows = math.ceil(#order / COLS)
local c = A.canvas(CELL_W * COLS, CELL_H * rows)
local chars = {}
for i, k in ipairs(order) do
  local g = G[k]
  local cx, cy = ((i - 1) % COLS) * CELL_W, ((i - 1) // COLS) * CELL_H
  for y, row in ipairs(g) do
    for x = 1, #row do
      if row:sub(x, x) == "#" then c:px(cx + x - 1, cy + y - 1, "ffffff") end
    end
  end
  chars[#chars + 1] = { ch = k, x = cx, y = cy, w = #g[1] }
end

local lines = {}
local function add(s) lines[#lines + 1] = s end
add('info face="BilliardKing" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0')
add(string.format("common lineHeight=10 base=7 scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4", c.w, c.h))
add('page id=0 file="font.png"')
local entries = {}
local function entry(code, ch)
  entries[#entries + 1] = string.format("char id=%d x=%d y=%d width=%d height=7 xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15", code, ch.x, ch.y, ch.w, ch.w + 1)
end
for _, ch in ipairs(chars) do
  entry(string.byte(ch.ch), ch)
  if ch.ch:match("%u") then entry(string.byte(ch.ch:lower()), ch) end
end
entries[#entries + 1] = "char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15"
add("chars count=" .. #entries)
for _, e in ipairs(entries) do add(e) end

c:save("font", "fonts")
local f = io.open(A.root .. "/assets/fonts/font.fnt", "w")
f:write(table.concat(lines, "\n") .. "\n")
f:close()
print("Font exported (" .. #entries .. " glyphs).")
